// Builds the paste-ready G1 files in docs/analytics/bigquery (docs/specs/analytics-v2.md §8.1)
// from their sources, so the fixture check always runs the same view SQL the CTO applies.
// `npm run analytics` writes them; metricsSql.test.ts fails if they are stale.

/** The objects to apply, in the order they depend on each other. */
export const VIEW_FILES = [
  'deleted_users.sql',
  'deleted_devices.sql',
  'events_people_all.sql',
  'events_clean_all.sql',
  'events_clean.sql',
  'events_people.sql',
];

/** A throwaway dataset holding fixture rows; the check drops it when it passes. */
export const SCRATCH_DATASET = 'onquest_analytics_g1_check';
const SCRATCH_VIEWS = ['events_people_all.sql', 'events_clean_all.sql'];
const MARKER = '-- @scratch-views\n';

/** g1_fixture_check.sql: fixture rows, the real views pointed at them, and the checks. */
export function renderFixtureCheck(read: (file: string) => string): string {
  const template = read('g1_fixture_check.template.sql');
  if (!template.includes(MARKER)) throw new Error(`g1_fixture_check.template.sql has no "${MARKER.trim()}" line`);
  const views = SCRATCH_VIEWS.map(
    (file) =>
      `-- ---- ${file}, reading the fixture tables ----\n` +
      read(file).replaceAll('`onquest_analytics.', `\`${SCRATCH_DATASET}.`),
  ).join('\n');
  return [
    '-- Generated by `npm run analytics` from g1_fixture_check.template.sql and the view files.',
    '-- Do not edit: change those and run the script again.',
    // A function, so the `$'` and `$&` in the view SQL aren't read as replacement patterns.
    template.replace(MARKER, () => views),
  ].join('\n');
}

/** apply-g1.sql: the checklist, Part A (fixture check) and Part B (the six objects). */
export function renderApplyG1(read: (file: string) => string): string {
  return [
    read('g1_checklist.sql'),
    '-- =============================================================================================',
    '-- PART A: fixture check. Paste from here to the PART B line and Run. It touches only the',
    `-- scratch dataset ${SCRATCH_DATASET}, never onquest_analytics.`,
    '-- =============================================================================================',
    renderFixtureCheck(read),
    '-- =============================================================================================',
    '-- PART B: apply. Paste from here to the end and Run (a separate run from Part A).',
    '-- =============================================================================================',
    VIEW_FILES.map((file) => `-- ==== ${file} ====\n${read(file)}`).join('\n'),
  ].join('\n');
}
