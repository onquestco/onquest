// Turns the Taxonomy sheet's CSV export (docs/analytics/*.csv) into lib/analytics/taxonomy.ts.
// The CSVs win (spec A §3.9): `npm run analytics` regenerates the file, and a test fails if it's stale.

export type PropertyType = 'STRING' | 'BOOL' | 'INT64' | 'FLOAT64';
export type PropertyRule = {
  type: PropertyType;
  required: boolean;
  /** One of these (STRING). */
  values?: string[];
  /** A comma list of some of these, e.g. "name,photo" (STRING). */
  list?: string[];
  /** Inclusive bounds (numbers). */
  min?: number;
  max?: number;
};
export type Taxonomy = Record<string, Record<string, PropertyRule>>;

/** RFC 4180-ish: commas, quoted fields with "" escapes, \n or \r\n rows. */
export function parseCsv(text: string): string[][] {
  const rows: string[][] = [];
  let row: string[] = [];
  let field = '';
  let quoted = false;
  for (let i = 0; i < text.length; i++) {
    const char = text[i];
    if (quoted) {
      if (char === '"' && text[i + 1] === '"') {
        field += '"';
        i++;
      } else if (char === '"') quoted = false;
      else field += char;
    } else if (char === '"') quoted = true;
    else if (char === ',') {
      row.push(field);
      field = '';
    } else if (char === '\n' || char === '\r') {
      if (char === '\r' && text[i + 1] === '\n') i++;
      row.push(field);
      rows.push(row);
      row = [];
      field = '';
    } else field += char;
  }
  if (field || row.length) rows.push([...row, field]);
  return rows.filter((cells) => cells.some((cell) => cell.trim()));
}

function rule(type: string, allowed: string, required: string): PropertyRule {
  const base: PropertyRule = { type: type as PropertyType, required: required.trim() === 'yes' };
  const text = allowed.trim();
  const range = /^(-?\d+(?:\.\d+)?)\s*[–-]\s*(-?\d+(?:\.\d+)?)$/.exec(text);
  if (range) return { ...base, min: Number(range[1]), max: Number(range[2]) };
  if (type !== 'STRING' || !text || /^(UUID|ISO .*|anon_<uuid>)$/.test(text)) return base;
  if (text.includes(' / ')) return { ...base, values: text.split(' / ').map((value) => value.trim()) };
  if (text.includes(',')) return { ...base, list: text.split(',').map((value) => value.trim()) };
  return { ...base, values: [text] };
}

/** An event's first row has its name; the rows after it with no name are more of its properties. */
export function taxonomyFromCsv(text: string): Taxonomy {
  const [header, ...rows] = parseCsv(text);
  const column = (name: string) => {
    const index = header?.findIndex((cell) => cell.trim().startsWith(name)) ?? -1;
    if (index < 0) throw new Error(`Taxonomy CSV has no "${name}" column`);
    return index;
  };
  const [nameAt, propertyAt, typeAt, allowedAt, requiredAt] = [
    column('name'),
    column('properties'),
    column('Data type'),
    column('Allowed values'),
    column('Required'),
  ];
  const taxonomy: Taxonomy = {};
  let current = '';
  for (const cells of rows) {
    current = cells[nameAt]?.trim() || current;
    if (!current) continue;
    const properties = (taxonomy[current] ??= {});
    const property = cells[propertyAt]?.trim() ?? '';
    if (!property || property.startsWith('(')) continue; // "(common only)"
    properties[property] = rule(cells[typeAt] ?? '', cells[allowedAt] ?? '', cells[requiredAt] ?? '');
  }
  return taxonomy;
}

/** The generated module's source. Stable key order, so a diff shows only real changes. */
export function renderTaxonomyModule(client: Taxonomy, server: Taxonomy): string {
  const sorted = (taxonomy: Taxonomy) =>
    Object.fromEntries(
      Object.keys(taxonomy)
        .sort()
        .map((name) => [name, taxonomy[name]]),
    );
  return [
    '// Generated by `npm run analytics` from docs/analytics/*.csv. Do not edit: change the sheet,',
    '// export it, and run the script again.',
    "import type { Taxonomy } from './taxonomyFromCsv';",
    '',
    `export const CLIENT_EVENTS = ${JSON.stringify(sorted(client), null, 2)} as const satisfies Taxonomy;`,
    '',
    `export const SERVER_EVENTS = ${JSON.stringify(sorted(server), null, 2)} as const satisfies Taxonomy;`,
    '',
    'export type ClientEventName = keyof typeof CLIENT_EVENTS;',
    'export type ServerEventName = keyof typeof SERVER_EVENTS;',
    '',
  ].join('\n');
}
